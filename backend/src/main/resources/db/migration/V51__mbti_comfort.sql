-- 추가 전용이다: 기존 행과 열은 건드리지 않는다.

ALTER TABLE profiles ADD COLUMN mbti VARCHAR(4);
ALTER TABLE profiles ADD CONSTRAINT profiles_mbti_check CHECK (mbti IS NULL OR mbti ~ '^[EI][SN][TF][JP]$');

-- 문구는 운영 중에 이 표에서 바로 고칠 수 있다 (서버는 10분 동안 기억했다가 다시 읽는다).
-- 일반적인 경향을 적은 초안이다: AI 에게는 "기록에 드러난 마음이 먼저"라는 규칙과 함께 참고 지침으로만 건넨다.
CREATE TABLE mbti_comfort_guides (
    mbti       VARCHAR(4) PRIMARY KEY CHECK (mbti ~ '^[EI][SN][TF][JP]$'),
    direction  TEXT NOT NULL,      -- 위로받고 싶어 하는 방향
