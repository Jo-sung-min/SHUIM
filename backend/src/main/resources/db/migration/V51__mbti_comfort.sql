    love       TEXT NOT NULL,      -- 사랑받기: 이렇게 건네면 닿는다
    avoid      TEXT NOT NULL,      -- 피할 말
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

